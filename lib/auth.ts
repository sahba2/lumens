const NETWORK_ERROR_MESSAGE =
  "ارتباط با سرور برقرار نشد؛ اتصال اینترنت را بررسی کرده و دوباره تلاش کنید.";

/** Converts a Supabase auth error into a human readable Persian message. */
export function translateAuthError(error: AuthError | Error | null | undefined): string {
  if (!error) {
    return "";
  }

  const code = "code" in error && typeof error.code === "string" ? error.code : null;
  if (code && AUTH_ERROR_MESSAGES[code]) {
    return AUTH_ERROR_MESSAGES[code];
  }

  const message = error.message ?? "";
  if (/network|fetch|failed to fetch/i.test(message)) {
    return NETWORK_ERROR_MESSAGE;
  }

  return "خطای غیرمنتظره‌ای رخ داد؛ لطفاً دوباره تلاش کنید.";
}

/** Validates the e-mail format before calling Supabase. */
export function isValidEmail(email: string): boolean {
  return EMAIL_PATTERN.test(email.trim());
}

/** Returns a localized validation error, or `null` when the password is valid. */
export function validatePassword(password: string): string | null {
  if (password.length < MIN_PASSWORD_LENGTH) {
    return `رمز عبور باید حداقل ${MIN_PASSWORD_LENGTH} کاراکتر باشد.`;
  }

  if (!/[A-Za-z]/.test(password) || !/\d/.test(password)) {
    return "رمز عبور باید ترکیبی از حروف و عدد باشد.";
  }

  return null;
}

/** True when the auth API can be reached (env variables are present). */
export function isAuthAvailable(): boolean {
  return isSupabaseConfigured();
}

function failure(message: string): AuthResult {
  return { user: null, session: null, error: message };
}

function actionFailure(message: string): AuthActionResult {
  return { error: message };
}

/**
 * Creates a new LUMENS account.
 * The profile row (display name + role) is generated by the
 * `on_auth_user_created` database trigger from the sign-up metadata.
 */
export async function signUpWithEmail(input: SignUpInput): Promise<AuthResult> {
  if (!isSupabaseConfigured()) {
    return failure(SUPABASE_SETUP_HINT);
  }

  const email = input.email.trim().toLowerCase();
  if (!isValidEmail(email)) {
    return failure("ایمیل وارد شده معتبر نیست.");
  }

  const passwordError = validatePassword(input.password);
  if (passwordError) {
    return failure(passwordError);
  }

  const fullName = input.fullName.trim();
  if (fullName.length < 3) {
    return failure("نام و نام خانوادگی را کامل وارد کنید.");
  }

  const { data, error } = await getSupabaseBrowserClient().auth.signUp({
    email,
    password: input.password,
    options: {
      emailRedirectTo: input.emailRedirectTo ?? `${supabaseConfig.siteUrl}/auth/callback`,
      data: {
        full_name: fullName,
        role: input.role ?? "student",
        locale: "fa-IR",
      },
    },
  });

  if (error) {
    return failure(translateAuthError(error));
  }

  return { user: data.user, session: data.session, error: null };
}

/** Signs an existing user in with e-mail + password. */
export async function signInWithEmail(input: SignInInput): Promise<AuthResult> {
  if (!isSupabaseConfigured()) {
    return failure(SUPABASE_SETUP_HINT);
  }

  const email = input.email.trim().toLowerCase();
  if (!isValidEmail(email)) {
    return failure("ایمیل وارد شده معتبر نیست.");
  }

  if (input.password.length === 0) {
    return failure("رمز عبور را وارد کنید.");
  }

  const { data, error } = await getSupabaseBrowserClient().auth.signInWithPassword({
    email,
    password: input.password,
  });

  if (error) {
    return failure(translateAuthError(error));
  }

  return { user: data.user, session: data.session, error: null };
}

/** Sends a passwordless magic link (login by default, optional sign-up). */
export async function signInWithMagicLink(
  email: string,
  options: { emailRedirectTo?: string; createUser?: boolean } = {},
): Promise<AuthActionResult> {
  if (!isSupabaseConfigured()) {
    return actionFailure(SUPABASE_SETUP_HINT);
  }

  const normalizedEmail = email.trim().toLowerCase();
  if (!isValidEmail(normalizedEmail)) {
    return actionFailure("ایمیل وارد شده معتبر نیست.");
  }

  const { error } = await getSupabaseBrowserClient().auth.signInWithOtp({
    email: normalizedEmail,
    options: {
      emailRedirectTo: options.emailRedirectTo ?? `${supabaseConfig.siteUrl}/auth/callback`,
      shouldCreateUser: options.createUser ?? false,
    },
  });

  return { error: error ? translateAuthError(error) : null };
}

/** Ends the current session and clears the auth cookies. */
export async function signOut(): Promise<AuthActionResult> {
  if (!isSupabaseConfigured()) {
    return actionFailure(SUPABASE_SETUP_HINT);
  }

  const { error } = await getSupabaseBrowserClient().auth.signOut();
  return { error: error ? translateAuthError(error) : null };
}

/** Sends the password recovery e-mail. */
export async function sendPasswordReset(
  email: string,
  redirectTo?: string,
): Promise<AuthActionResult> {
  if (!isSupabaseConfigured()) {
    return actionFailure(SUPABASE_SETUP_HINT);
  }

  const normalizedEmail = email.trim().toLowerCase();
  if (!isValidEmail(normalizedEmail)) {
    return actionFailure("ایمیل وارد شده معتبر نیست.");
  }

  const { error } = await getSupabaseBrowserClient().auth.resetPasswordForEmail(normalizedEmail, {
    redirectTo: redirectTo ?? `${supabaseConfig.siteUrl}/auth/callback?next=/auth/reset-password`,
  });

  return { error: error ? translateAuthError(error) : null };
}

/** Sets a new password for the signed-in (or recovery) session. */
export async function updatePassword(password: string): Promise<AuthActionResult> {
  if (!isSupabaseConfigured()) {
    return actionFailure(SUPABASE_SETUP_HINT);
  }

  const passwordError = validatePassword(password);
  if (passwordError) {
    return actionFailure(passwordError);
  }

  const { error } = await getSupabaseBrowserClient().auth.updateUser({ password });
  return { error: error ? translateAuthError(error) : null };
}

/** Reads the current session from cookies/storage. */
export async function getSession(): Promise<SessionResult> {
  if (!isSupabaseConfigured()) {
    return { session: null, error: SUPABASE_SETUP_HINT };
  }

  const { data, error } = await getSupabaseBrowserClient().auth.getSession();
  return { session: data.session, error: error ? translateAuthError(error) : null };
}

/** Returns the authenticated user, validated against the Auth server. */
export async function getCurrentUser(): Promise<UserResult> {
  if (!isSupabaseConfigured()) {
    return { user: null, error: SUPABASE_SETUP_HINT };
  }

  const { data, error } = await getSupabaseBrowserClient().auth.getUser();
  return { user: data.user, error: error ? translateAuthError(error) : null };
}

/** Subscribes to auth events; returns `null` when Supabase is not configured. */
export function onAuthStateChange(
  callback: (event: AuthChangeEvent, session: Session | null) => void,
): Subscription | null {
  if (!isSupabaseConfigured()) {
    return null;
  }

  const { data } = getSupabaseBrowserClient().auth.onAuthStateChange(callback);
  return data.subscription;
}

