/**
 * LUMENS - authentication helpers (browser)
 * -----------------------------------------
 * Thin, localized wrappers around Supabase Auth for e-mail sign-up, login,
 * magic links, password recovery and session inspection.
 * All functions are safe to call from Client Components; they never throw for
 * expected auth failures and instead return a Persian `error` message.
 */

import type { AuthChangeEvent, AuthError, Session, Subscription, User } from "@supabase/supabase-js";

import type { UserRole } from "./database.types";
import {
  SUPABASE_SETUP_HINT,
  getSupabaseBrowserClient,
  isSupabaseConfigured,
  supabaseConfig,
} from "./supabase";

/** Minimum password length enforced before hitting the Supabase API. */
export const MIN_PASSWORD_LENGTH = 8;

/** Roles a visitor is allowed to pick at sign-up (staff roles are admin-only). */
export type SignUpRole = Extract<UserRole, "student" | "instructor">;

export interface SignUpInput {
  email: string;
  password: string;
  fullName: string;
  role?: SignUpRole;
  /** Absolute URL the confirmation e-mail should return to. */
  emailRedirectTo?: string;
}

export interface SignInInput {
  email: string;
  password: string;
}

export interface AuthResult {
  user: User | null;
  session: Session | null;
  error: string | null;
}

export interface AuthActionResult {
  error: string | null;
}

export interface SessionResult {
  session: Session | null;
  error: string | null;
}

export interface UserResult {
  user: User | null;
  error: string | null;
}

